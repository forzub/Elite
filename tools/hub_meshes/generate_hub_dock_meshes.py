"""Generate the hex dock, its fixed service block and the orbital cargo shuttle
as OBJ (meters, +X right, +Y up, -Z forward / nose). Numbers mirror
src/game/docking/model/HexDockFacility.h; keep them in sync.

    python tools/hub_meshes/generate_hub_dock_meshes.py

Faces are convex planar polygons (the OBJ loader keeps polygons, so Elite
edges follow polygon borders), oriented by an explicit outward normal.
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# --- HexDockFacility.h ---------------------------------------------------------
OUTER_APOTHEM = 150.0
INNER_APOTHEM = 120.0
ENTRY_Z, CHAMBER_FRONT_Z, CHAMBER_BACK_Z, BACK_Z = -200.0, -100.0, 180.0, 200.0
SLOT_W, SLOT_H = 160.0, 60.0
PORT_HALF = 20.0
PAD_Z, PAD_LEN, PAD_W, PAD_T = 60.0, 70.0, 56.0, 2.0
SERVICE_HALF_LEN, SERVICE_HALF, BORE_HALF = 300.0, 120.0, 40.0


def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


class Mesh:
    def __init__(self, title):
        self.title = title
        self.v = []
        self.f = []
        self.boxes = []

    def poly(self, pts, outward):
        if len(pts) < 3:
            return
        n = cross(sub(pts[1], pts[0]), sub(pts[2], pts[0]))
        # robust normal for convex polygons
        for i in range(2, len(pts)):
            c = cross(sub(pts[i - 1], pts[0]), sub(pts[i], pts[0]))
            if dot(c, c) > dot(n, n):
                n = c
        if dot(n, outward) < 0:
            pts = list(reversed(pts))
        base = len(self.v)
        self.v.extend(pts)
        self.f.append([base + i + 1 for i in range(len(pts))])

    def box(self, center, half, name=None, collide=True):
        cx, cy, cz = center
        hx, hy, hz = half
        def P(sx, sy, sz): return (cx + sx * hx, cy + sy * hy, cz + sz * hz)
        self.poly([P(1, -1, -1), P(1, 1, -1), P(1, 1, 1), P(1, -1, 1)], (1, 0, 0))
        self.poly([P(-1, -1, -1), P(-1, -1, 1), P(-1, 1, 1), P(-1, 1, -1)], (-1, 0, 0))
        self.poly([P(-1, 1, -1), P(-1, 1, 1), P(1, 1, 1), P(1, 1, -1)], (0, 1, 0))
        self.poly([P(-1, -1, -1), P(1, -1, -1), P(1, -1, 1), P(-1, -1, 1)], (0, -1, 0))
        self.poly([P(-1, -1, 1), P(1, -1, 1), P(1, 1, 1), P(-1, 1, 1)], (0, 0, 1))
        self.poly([P(-1, -1, -1), P(-1, 1, -1), P(1, 1, -1), P(1, -1, -1)], (0, 0, -1))
        if collide and name:
            self.boxes.append((name, center, half))

    def write(self, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', newline='\n') as out:
            out.write('# %s\n# Generated by tools/hub_meshes/generate_hub_dock_meshes.py - do not edit by hand.\n' % self.title)
            for p in self.v:
                out.write('v %.4f %.4f %.4f\n' % p)
            for face in self.f:
                out.write('f ' + ' '.join(str(i) for i in face) + '\n')
        print('%s: %d vertices, %d polygons -> %s' % (self.title, len(self.v), len(self.f), os.path.relpath(path, ROOT)))


def hexagon(apothem):
    r = apothem / math.cos(math.radians(30.0))
    return [(r * math.cos(math.radians(60.0 * i)), r * math.sin(math.radians(60.0 * i))) for i in range(6)]


def clip(poly, a, b, c):
    """Keep the part of a 2D convex polygon with a*x + b*y <= c."""
    out = []
    for i in range(len(poly)):
        p, q = poly[i], poly[(i + 1) % len(poly)]
        fp, fq = a * p[0] + b * p[1] - c, a * q[0] + b * q[1] - c
        if fp <= 1e-9:
            out.append(p)
        if (fp < -1e-9 and fq > 1e-9) or (fp > 1e-9 and fq < -1e-9):
            t = fp / (fp - fq)
            out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    return out


def ring_pieces(outer, hx, hy):
    """Outer convex polygon minus the rectangle |x|<=hx, |y|<=hy: 4 convex pieces."""
    top = clip(outer, 0, -1, -hy)          # y >= hy
    bottom = clip(outer, 0, 1, -hy)        # y <= -hy
    left = clip(clip(clip(outer, 1, 0, -hx), 0, 1, hy), 0, -1, hy)
    right = clip(clip(clip(outer, -1, 0, -hx), 0, 1, hy), 0, -1, hy)
    return [p for p in (top, bottom, left, right) if len(p) >= 3]


def face_at(poly2d, z):
    return [(x, y, z) for x, y in poly2d]


def tube(mesh, hx, hy, z0, z1):
    """Inward-facing rectangular tube walls (a passage)."""
    mesh.poly([(-hx, hy, z0), (hx, hy, z0), (hx, hy, z1), (-hx, hy, z1)], (0, -1, 0))
    mesh.poly([(-hx, -hy, z0), (hx, -hy, z0), (hx, -hy, z1), (-hx, -hy, z1)], (0, 1, 0))
    mesh.poly([(-hx, -hy, z0), (-hx, hy, z0), (-hx, hy, z1), (-hx, -hy, z1)], (1, 0, 0))
    mesh.poly([(hx, -hy, z0), (hx, hy, z0), (hx, hy, z1), (hx, -hy, z1)], (-1, 0, 0))


def hex_dock():
    m = Mesh('Hub hex dock (rotating body)')
    outer, inner = hexagon(OUTER_APOTHEM), hexagon(INNER_APOTHEM)
    # Outer side walls and inner chamber walls.
    for i in range(6):
        a, b = outer[i], outer[(i + 1) % 6]
        n = (math.cos(math.radians(30 + 60 * i)), math.sin(math.radians(30 + 60 * i)), 0.0)
        m.poly([(a[0], a[1], ENTRY_Z), (b[0], b[1], ENTRY_Z), (b[0], b[1], BACK_Z), (a[0], a[1], BACK_Z)], n)
        a, b = inner[i], inner[(i + 1) % 6]
        m.poly([(a[0], a[1], CHAMBER_FRONT_Z), (b[0], b[1], CHAMBER_FRONT_Z), (b[0], b[1], CHAMBER_BACK_Z),
                (a[0], a[1], CHAMBER_BACK_Z)], (-n[0], -n[1], 0.0))
    # Front face with the slot, entry corridor, chamber front wall.
    for piece in ring_pieces(outer, SLOT_W / 2, SLOT_H / 2):
        m.poly(face_at(piece, ENTRY_Z), (0, 0, -1))
    tube(m, SLOT_W / 2, SLOT_H / 2, ENTRY_Z, CHAMBER_FRONT_Z)
    for piece in ring_pieces(inner, SLOT_W / 2, SLOT_H / 2):
        m.poly(face_at(piece, CHAMBER_FRONT_Z), (0, 0, 1))
    # Back: chamber back wall, service port into the block tunnel, back face.
    for piece in ring_pieces(inner, PORT_HALF, PORT_HALF):
        m.poly(face_at(piece, CHAMBER_BACK_Z), (0, 0, -1))
    tube(m, PORT_HALF, PORT_HALF, CHAMBER_BACK_Z, BACK_Z)
    for piece in ring_pieces(outer, PORT_HALF, PORT_HALF):
        m.poly(face_at(piece, BACK_Z), (0, 0, 1))
    # Six pads, one per inner wall (thin plates on the wall, along the axis).
    for k in range(6):
        ang = math.radians(30 + 60 * k)
        n = (math.cos(ang), math.sin(ang))
        t = (-n[1], n[0])
        r0, r1 = INNER_APOTHEM - PAD_T, INNER_APOTHEM
        corners = []
        for rr in (r0, r1):
            for tt in (-PAD_W / 2, PAD_W / 2):
                corners.append((n[0] * rr + t[0] * tt, n[1] * rr + t[1] * tt))
        zs = (PAD_Z - PAD_LEN / 2, PAD_Z + PAD_LEN / 2)
        top = [corners[0], corners[1]]  # inner face (r0) faces the axis
        m.poly([(top[0][0], top[0][1], zs[0]), (top[1][0], top[1][1], zs[0]), (top[1][0], top[1][1], zs[1]),
                (top[0][0], top[0][1], zs[1])], (-n[0], -n[1], 0))
        for side in ((0, 2), (1, 3)):
            p, q = corners[side[0]], corners[side[1]]
            out = (t[0] * (1 if side[0] == 1 else -1), t[1] * (1 if side[0] == 1 else -1), 0)
            m.poly([(p[0], p[1], zs[0]), (q[0], q[1], zs[0]), (q[0], q[1], zs[1]), (p[0], p[1], zs[1])], out)
        for z, nz in ((zs[0], -1), (zs[1], 1)):
            m.poly([(corners[0][0], corners[0][1], z), (corners[1][0], corners[1][1], z),
                    (corners[3][0], corners[3][1], z), (corners[2][0], corners[2][1], z)], (0, 0, nz))
        # Pad centre mark: a raised strip across the pad (landing "T" cue).
        cx, cy = n[0] * (r0 - 0.5), n[1] * (r0 - 0.5)
        m.box((cx, cy, PAD_Z - PAD_LEN / 2 + 6.0), (abs(t[0]) * 18 + abs(n[0]) * 0.5 + 0.01,
                                                     abs(t[1]) * 18 + abs(n[1]) * 0.5 + 0.01, 1.5), collide=False)
    # Entry guide: apron under the slot (DOWN cue) + portal frame in front.
    m.box((0.0, -SLOT_H / 2 - 4.0, ENTRY_Z - 30.0), (SLOT_W / 2, 4.0, 30.0), 'apron')
    for sx in (-1, 1):
        m.box((sx * 100.0, 0.0, ENTRY_Z - 45.0), (10.0, 44.0, 45.0), 'guide_pylon_%s' % ('left' if sx < 0 else 'right'))
    m.box((0.0, 48.0, ENTRY_Z - 82.0), (110.0, 4.0, 8.0), 'guide_beam')
    # Collision: outer walls between the apothems, front / back plates with
    # their openings (the chamber and the corridor stay free).
    for i in range(6):
        ang = math.radians(30 + 60 * i)
        rc = (OUTER_APOTHEM + INNER_APOTHEM) / 2
        m.boxes.append(('wall_%d' % (i + 1), (rc * math.cos(ang), rc * math.sin(ang), 0.0),
                        ((OUTER_APOTHEM - INNER_APOTHEM) / 2, OUTER_APOTHEM / math.cos(math.radians(30)) / 2, (BACK_Z - ENTRY_Z) / 2),
                        30 + 60 * i))
    zc, hz = (ENTRY_Z + CHAMBER_FRONT_Z) / 2, (CHAMBER_FRONT_Z - ENTRY_Z) / 2
    w = OUTER_APOTHEM / math.cos(math.radians(30))
    m.boxes.append(('front_top', (0.0, (SLOT_H / 2 + INNER_APOTHEM) / 2, zc), (w, (INNER_APOTHEM - SLOT_H / 2) / 2, hz)))
    m.boxes.append(('front_bottom', (0.0, -(SLOT_H / 2 + INNER_APOTHEM) / 2, zc), (w, (INNER_APOTHEM - SLOT_H / 2) / 2, hz)))
    xs = (SLOT_W / 2 + w) / 2
    m.boxes.append(('front_left', (-xs, 0.0, zc), ((w - SLOT_W / 2) / 2, SLOT_H / 2, hz)))
    m.boxes.append(('front_right', (xs, 0.0, zc), ((w - SLOT_W / 2) / 2, SLOT_H / 2, hz)))
    zb, hb = (CHAMBER_BACK_Z + BACK_Z) / 2, (BACK_Z - CHAMBER_BACK_Z) / 2
    m.boxes.append(('back_top', (0.0, (PORT_HALF + INNER_APOTHEM) / 2, zb), (w, (INNER_APOTHEM - PORT_HALF) / 2, hb)))
    m.boxes.append(('back_bottom', (0.0, -(PORT_HALF + INNER_APOTHEM) / 2, zb), (w, (INNER_APOTHEM - PORT_HALF) / 2, hb)))
    m.boxes.append(('back_left', (-(PORT_HALF + w) / 2, 0.0, zb), ((w - PORT_HALF) / 2, PORT_HALF, hb)))
    m.boxes.append(('back_right', ((PORT_HALF + w) / 2, 0.0, zb), ((w - PORT_HALF) / 2, PORT_HALF, hb)))
    return m


def service_block():
    m = Mesh('Hub dock service block (fixed)')
    H, B, L = SERVICE_HALF, BORE_HALF, SERVICE_HALF_LEN
    sq = [(-H, -H), (H, -H), (H, H), (-H, H)]
    for (a, b), n in zip(zip(sq, sq[1:] + sq[:1]), [(0, -1, 0), (1, 0, 0), (0, 1, 0), (-1, 0, 0)]):
        m.poly([(a[0], a[1], -L), (b[0], b[1], -L), (b[0], b[1], L), (a[0], a[1], L)], n)
    tube(m, B, B, -L, L)
    for piece in ring_pieces(sq, B, B):
        m.poly(face_at(piece, -L), (0, 0, -1))
        m.poly(face_at(piece, L), (0, 0, 1))
    # Radiator wings on +/-X, service gantry ribs.
    for sx in (-1, 1):
        m.box((sx * (H + 90.0), 0.0, 0.0), (90.0, 1.0, 220.0), 'radiator_%s' % ('left' if sx < 0 else 'right'))
    for z in (-200.0, 0.0, 200.0):
        m.box((0.0, H + 3.0, z), (H, 3.0, 6.0), collide=False)
    m.boxes.append(('tube_top', (0.0, (H + B) / 2, 0.0), (H, (H - B) / 2, L)))
    m.boxes.append(('tube_bottom', (0.0, -(H + B) / 2, 0.0), (H, (H - B) / 2, L)))
    m.boxes.append(('tube_left', (-(H + B) / 2, 0.0, 0.0), ((H - B) / 2, B, L)))
    m.boxes.append(('tube_right', ((H + B) / 2, 0.0, 0.0), ((H - B) / 2, B, L)))
    return m


def cargo_shuttle():
    m = Mesh('OCS-4 orbital cargo shuttle')
    # Hull 18 x 14 x 44 (z -28 .. 16), nose chamfer, cylindrical main engine.
    hx, hy = 9.0, 7.0
    z0, z1, zc = -28.0, 16.0, -22.0
    # Main box from the chamfer to the engine end.
    m.poly([(hx, -hy, zc), (hx, hy, zc - 3.0), (hx, hy, z1), (hx, -hy, z1)], (1, 0, 0))
    m.poly([(-hx, -hy, zc), (-hx, -hy, z1), (-hx, hy, z1), (-hx, hy, zc - 3.0)], (-1, 0, 0))
    m.poly([(-hx, -hy, z0), (hx, -hy, z0), (hx, -hy, z1), (-hx, -hy, z1)], (0, -1, 0))
    m.poly([(-hx, hy, zc - 3.0), (hx, hy, zc - 3.0), (hx, hy, z1), (-hx, hy, z1)], (0, 1, 0))
    m.poly([(-hx, -hy, z1), (hx, -hy, z1), (hx, hy, z1), (-hx, hy, z1)], (0, 0, 1))
    # Nose: flat lower front, sloped cockpit glass upper front.
    m.poly([(-hx, -hy, z0), (-hx, 0.0, z0), (hx, 0.0, z0), (hx, -hy, z0)], (0, 0, -1))
    m.poly([(-hx, 0.0, z0), (-hx, hy, zc - 3.0), (hx, hy, zc - 3.0), (hx, 0.0, z0)], (0, 0.6, -1))
    m.poly([(hx, -hy, z0), (hx, 0.0, z0), (hx, hy, zc - 3.0), (hx, -hy, zc)], (1, 0, 0))
    m.poly([(-hx, -hy, z0), (-hx, -hy, zc), (-hx, hy, zc - 3.0), (-hx, 0.0, z0)], (-1, 0, 0))
    # Engine: octagonal cylinder r 5 (z 16..26) + bell r 5 -> 6.5 (z 26..28).
    seg = 8
    ring = lambda r, z: [(r * math.cos(2 * math.pi * i / seg + math.pi / seg),
                          r * math.sin(2 * math.pi * i / seg + math.pi / seg), z) for i in range(seg)]
    a, b, c = ring(5.0, z1), ring(5.0, 26.0), ring(6.5, 28.0)
    for i in range(seg):
        j = (i + 1) % seg
        mid = ((a[i][0] + a[j][0]) / 2, (a[i][1] + a[j][1]) / 2, 0.0)
        m.poly([a[i], a[j], b[j], b[i]], mid)
        m.poly([b[i], b[j], c[j], c[i]], mid)
    m.poly(list(reversed(c)), (0, 0, 1))
    # Cargo bay seam and two RCS quads (small boxes).
    for sx in (-1, 1):
        m.box((sx * (hx + 0.8), 0.0, -6.0), (0.8, 1.2, 1.2), collide=False)
        m.box((sx * (hx + 0.8), 0.0, 10.0), (0.8, 1.2, 1.2), collide=False)
    m.box((0.0, hy + 0.4, -4.0), (6.0, 0.4, 12.0), collide=False)
    return m


def write_boxes_header(mesh, path, namespace, func):
    lines = ['#pragma once', '', '// Generated by tools/hub_meshes/generate_hub_dock_meshes.py - do not edit by hand.',
             '// Collision OBBs of "%s" in its local frame.' % mesh.title, '', '#include <vector>', '',
             '#include <glm/glm.hpp>', '#include <glm/gtc/matrix_transform.hpp>', '',
             '#include "src/world/descriptors/IObjectDescriptor.h"', '', 'namespace %s' % namespace, '{', '',
             'inline const std::vector<LogicalCollisionBox>& %s()' % func, '{',
             '    static const std::vector<LogicalCollisionBox> boxes = [] {',
             '        std::vector<LogicalCollisionBox> out;']
    for entry in mesh.boxes:
        name, c, h = entry[0], entry[1], entry[2]
        rot = entry[3] if len(entry) > 3 else 0.0
        if rot:
            lines.append('        out.push_back({glm::vec3(%.3ff, %.3ff, %.3ff), glm::vec3(%.3ff, %.3ff, %.3ff),' % (c + h))
            lines.append('            glm::mat3(glm::rotate(glm::mat4(1.0f), glm::radians(%.1ff), glm::vec3(0, 0, 1))), "%s"});' % (rot, name))
        else:
            lines.append('        out.push_back({glm::vec3(%.3ff, %.3ff, %.3ff), glm::vec3(%.3ff, %.3ff, %.3ff), glm::mat3(1.0f), "%s"});' % (c + h + (name,)))
    lines += ['        return out;', '    }();', '    return boxes;', '}', '', '} // namespace %s' % namespace, '']
    with open(path, 'w', newline='\n') as out:
        out.write('\n'.join(lines))
    print('%d collision boxes -> %s' % (len(mesh.boxes), os.path.relpath(path, ROOT)))


