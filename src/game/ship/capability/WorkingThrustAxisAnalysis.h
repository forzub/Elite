#pragma once

// Pure, layout-independent geometry for a propulsion reference.
//
// The propulsion plant owns all physical candidates and ultimately validates
// the actuator command. MotherComputer can choose a strategic heading only
// among these feasible candidates. This routine has no client/server, HUD,
// autopilot, BITE, or simulation dependencies.
//
// Body coordinates: +X starboard, +Y up, -Z nose/forward.
// Forward aft engines supply force near -Z; their exhaust points opposite
// the actual force. Distances are measured from the CURRENT centre of mass.

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <limits>
#include <vector>
#include <glm/glm.hpp>

namespace game::ship::capability
{

struct ForwardMotorGeometry
{
    std::size_t slotIndex = 0;
    glm::dvec3 armFromComMeters {0.0};
    double availableThrustNewtons = 0.0;
    double availableConeRad = 0.0;
};

struct FeasibleWorkingAxis
{
    bool hasUsableThrust = false;
    // If true, conventional -Z is achievable with torque-neutral
    // nonnegative, individually feasible motor thrust contributions.
    bool centeredForwardAvailable = false;
    // An outboard thrust-axis fallback may use only ONE of several motors
    // until the multi-motor 6D joint allocator proves a stronger solution.
    bool offAxis = false;
    glm::dvec3 forceDirectionBody {0.0,0.0,-1.0};
    double axisOffsetRad = 0.0;
    std::size_t preferredAftSlot = std::numeric_limits<std::size_t>::max();
    double conservativeMotorForceNewtons = 0.0;
};

namespace working_axis_detail
{
inline bool positive(double x) noexcept
{
    return std::isfinite(x) && x > 1.0e-9;
}

// Is the CoM's (x,y) origin in a cone generated by the projection of
// available positive-thrust motor positions? Caratheodory in 2D means at
// most three motors are needed to prove a nonnegative solution.
inline bool conventionalAxialRayFeasible(
    const std::vector<ForwardMotorGeometry>& motors
) noexcept
{
    constexpr double eps=1.0e-7;
    const auto alive=[](const ForwardMotorGeometry& m)
    {
        return positive(m.availableThrustNewtons) &&
            (std::isfinite(m.armFromComMeters.x) &&
             std::isfinite(m.armFromComMeters.y) &&
             std::isfinite(m.armFromComMeters.z));
    };
    // A real hull's CoM is never exactly on the motors' line (equipment,
    // cargo, fuel). A CoM within a small TRIM distance of that line is still
    // reached by gimballing the nozzles: each motor may tilt its thrust by at
    // most min(its cone, MaxTrimRad), so its line of action shifts by
    // |arm.z| * tan(tilt) at the CoM plane while the bank keeps pushing along
    // -Z. Exactly-centred hulls (Cobra: CoM at the origin) are unaffected.
    const auto trim=[](const ForwardMotorGeometry& m)
    {
        const double cone=std::isfinite(m.availableConeRad)
            ? std::clamp(m.availableConeRad,0.0,0.0349) : 0.0;   // trim <= 2 deg
        return std::abs(m.armFromComMeters.z)*std::tan(cone);
    };
    const std::size_t n=motors.size();
    for(std::size_t i=0;i<n;++i)
    {
        if(!alive(motors[i])) continue;
        const auto a=motors[i].armFromComMeters;
        if(std::hypot(a.x,a.y)<std::max(eps,trim(motors[i])))
            return true;
        for(std::size_t j=i+1;j<n;++j)
        {
            if(!alive(motors[j])) continue;
            const auto b=motors[j].armFromComMeters;
            const double determinant=a.x*b.y-a.y*b.x;
            const double dot=a.x*b.x+a.y*b.y;
            // An opposite pair with positive available forces can be
            // balanced by throttling, regardless of mismatched ratings.
            if(std::abs(determinant)<eps &&
                dot < -eps)
                return true;
            // ... and so can a pair whose segment passes within the trim
            // distance of the CoM (perpendicular offset, CoM between them).
            const double abx=b.x-a.x, aby=b.y-a.y;
            const double ab2=abx*abx+aby*aby;
            if(ab2>eps)
            {
                const double along=-(a.x*abx+a.y*aby);   // (0 - a) . (b - a)
                const double offset=std::abs(determinant)/std::sqrt(ab2);
                if(along>=0.0 && along<=ab2 &&
                    offset<=std::min(trim(motors[i]),trim(motors[j])))
                    return true;
            }
            for(std::size_t k=j+1;k<n;++k)
            {
                if(!alive(motors[k])) continue;
                const auto c=motors[k].armFromComMeters;
                const double crossBC=b.x*c.y-b.y*c.x;
                const double crossCA=c.x*a.y-c.y*a.x;
                const double crossAB=determinant;
                const double total=crossBC+crossCA+crossAB;
                if(std::abs(total)<eps) continue;
                // Barycentric coordinates of the origin inside the
                // triangle, allowing a zero weight on one side.
                const double wa=crossBC/total;
                const double wb=crossCA/total;
                const double wc=crossAB/total;
                if(wa>=-eps && wb>=-eps && wc>=-eps)
                    return true;
            }
        }
    }
    return false;
}
} // namespace working_axis_detail

[[nodiscard]] inline FeasibleWorkingAxis analyzeWorkingThrustGeometry(
    const std::vector<ForwardMotorGeometry>& aftMotors
) noexcept
{
    FeasibleWorkingAxis out;
    for(const auto& motor:aftMotors)
        out.hasUsableThrust |= working_axis_detail::positive(
            motor.availableThrustNewtons
        );
    if(!out.hasUsableThrust)
        return out;

    if(working_axis_detail::conventionalAxialRayFeasible(aftMotors))
    {
        out.centeredForwardAvailable=true;
        out.forceDirectionBody={0.0,0.0,-1.0};
        return out;
    }

    // No demonstrably balanced conventional thrust axis. Fall back to a
    // single center-of-mass ray. Choosing one feasible motor is deliberately
    // conservative: it guarantees zero propulsion torque irrespective of
    // the location, capability or health of the OTHER engines.
    double bestScore=-1.0;
    for(const auto& m:aftMotors)
    {
        if(!working_axis_detail::positive(m.availableThrustNewtons) ||
            !std::isfinite(m.availableConeRad) ||
            m.availableConeRad<0.0 ||
            !(std::isfinite(m.armFromComMeters.x) &&
             std::isfinite(m.armFromComMeters.y) &&
             std::isfinite(m.armFromComMeters.z)))
            continue;
        const double armLength=glm::length(m.armFromComMeters);
        if(armLength<=1.0e-9) continue;
        const auto force=-m.armFromComMeters/armLength;
        if(force.z>=-1.0e-9) continue;
        const double angle=std::acos(
            std::clamp(-force.z,-1.0,1.0)
        );
        if(angle>m.availableConeRad+1.0e-9)
            continue;
        // Prefer usable course-aligned force; then reduced nose offset.
        const double score=m.availableThrustNewtons*(-force.z);
        if(score <= bestScore) continue;
        bestScore=score;
        out.offAxis = angle>1.0e-8;
        out.forceDirectionBody=force;
        out.axisOffsetRad=angle;
        out.preferredAftSlot=m.slotIndex;
        out.conservativeMotorForceNewtons=m.availableThrustNewtons;
    }
    return out;
}
} // namespace game::ship::capability
