"""Put a generated belt settlement into the world (author 2026-11-17: «можешь сделать генератор для такого типа
структур? основное - каждый хаб уникален, повторяемость - один и тот же хаб имеет одинаковый вид каждый раз как к нему
приезжаешь»).

For a hub id (default belt_demo) this writes / refreshes the orbital hub <id> in src/assets/data/initial_world_state.json
(co-orbiting the Ceres hub a little ahead): one dock module "hub_belt_city" (ObjectType::HubBeltCity - its package is
assets/compiled/hub_modules/hub_<id>, the assembly generated by tools/models/units/hub_belt.py belt_layout(<id>)) and
one dock module per spinning body (the ring, habitat drums, hotel barrels - hubb_ring_core / hubb_hab_drum /
hubb_hotel_hex, angular_velocity_deg_s about their own Z). The layout is a pure function of the id: running it again
gives the same settlement. Haze sources -> src/assets/data/<id>_haze.json.

The assembly itself must be built first (build_equipment_models.py writes the hub_<id> set for the ids in
hub_belt.BELT_HUBS) and packaged by the mesh editor (hub_modules/hub_<id>).
usage: python tools/models/hub_belt_world.py [--hub belt_demo] [--phase-deg 0.0006]
"""
import argparse
import copy
import glob
import json
import math
import os
import shutil
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import eqlib  # noqa: E402

WORLD = os.path.join(ROOT, "src", "assets", "data", "initial_world_state.json")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub", default="belt_demo")
    ap.add_argument("--name", default=None)                      # default: the hub's current name
    ap.add_argument("--phase-deg", type=float, default=None)     # ahead of the Ceres hub on its orbit (0.0006 deg ~4300 km)
    a = ap.parse_args()
    from units.hub_plane import hub_layout as belt_layout   # the planar cities (PLANE_HUBS) or the belt settlement
    L = belt_layout(a.hub)
    world = json.loads(open(WORLD, encoding="utf-8").read())
    hubs = world["orbital_hubs"]
    ceres = next(h for h in hubs if h["id"] == "site.000.sol.ceres")
    if a.name is None:
        a.name = next((h["name"] for h in hubs if h["id"] == a.hub), "Поселение «Пояс» (генератор)")
    hub = {
        "id": a.hub, "name": a.name, "owner": "prototype", "operator": "prototype",
        "role": "поселение в поясе астероидов, сгенерировано по id (tools/models/units/hub_belt.py)",
        "system_id": ceres["system_id"], "parent_body_id": ceres["parent_body_id"], "map_object_module_id": "",
        "model_family": "hub_belt", "traffic_profile": {"profile": "mining", "arrivals_day": 0, "dock_sectors": 0},
        "motion": copy.deepcopy(ceres["motion"]), "modules": [],
        "note": "generated by tools/models/hub_belt_world.py; not in the canon",
        "dock_modules": [{"id": f"{a.hub}.city", "type": "hub_belt_city", "name": "city",
                          "offset_m": {"x": 0.0, "y": 0.0, "z": 0.0}, "rotation_deg": {"x": 0.0, "y": 0.0, "z": 0.0}}]}
    old = next((h for h in hubs if h["id"] == a.hub), None)
    if a.phase_deg is not None:
        hub["motion"]["initial_phase_deg"] = round(ceres["motion"]["initial_phase_deg"] + a.phase_deg, 7)
    elif old:                                                   # a rebuild (the hub editor) keeps the hub where it is
        hub["motion"]["initial_phase_deg"] = old["motion"]["initial_phase_deg"]
    else:                                                       # a new hub: the next free slot, 0.0006 deg apart
        gen = [h for h in hubs if h.get("model_family") == "hub_belt"]
        hub["motion"]["initial_phase_deg"] = round(ceres["motion"]["initial_phase_deg"] + 0.0006 * (len(gen) + 1), 7)
    hub["motion"]["self_rotation_period_seconds"] = 1.0e7
    for sp in L["spinning"]:
        p, r = sp["position"], sp["rotation_deg"]
        hub["dock_modules"].append({"id": f"{a.hub}.{sp['id']}", "type": sp["module"], "name": sp["title"],
                                    "offset_m": {"x": round(p[0], 3), "y": round(p[1], 3), "z": round(p[2], 3)},
                                    "rotation_deg": {"x": r[0], "y": r[1], "z": r[2]},
                                    "angular_velocity_deg_s": {"x": 0.0, "y": 0.0, "z": sp["rate_deg_s"]}})
    # docks (the planar city has one): the hub's own module ids, the navigation anchors and the port state copied from
    # the reference hex dock entry (hub_hex_dock_a) - the docking target is (module id, anchor id)
    nav = os.path.join(ROOT, "src", "assets", "data", "navigation")
    anchors = json.loads(open(os.path.join(nav, "hub_semantic_anchors.json"), encoding="utf-8").read())
    ports = json.loads(open(os.path.join(nav, "hub_docking_runtime_test.json"), encoding="utf-8").read())
    mine = lambda mid: mid.startswith(a.hub + ".")
    # a rebuild (the hub editor) puts the hub's entries back where they were: the files' order stays
    at_a = next((k for k, m in enumerate(anchors["modules"]) if mine(m["module_id"])), len(anchors["modules"]))
    at_p = next((k for k, p in enumerate(ports["ports"]) if mine(p["module_id"])), len(ports["ports"]))
    anchors["modules"] = [m for m in anchors["modules"] if not mine(m["module_id"])]
    ports["ports"] = [p for p in ports["ports"] if not mine(p["module_id"])]
    new_anchors, new_ports = [], []
    ref = {"hub_hex_dock": next(m for m in anchors["modules"] if m["module_id"] == "hub_hex_dock_a")}
    for dk in L.get("docks", []):
        p, r = dk["position"], dk["rotation_deg"]
        mid = f"{a.hub}.{dk['id']}"
        hub["dock_modules"].append({"id": mid, "type": dk["type"], "name": dk["name"],
                                    "offset_m": {"x": round(p[0], 3), "y": round(p[1], 3), "z": round(p[2], 3)},
                                    "rotation_deg": {"x": r[0], "y": r[1], "z": r[2]},
                                    "angular_velocity_deg_s": {"x": 0.0, "y": 0.0, "z": dk["spin_deg_s"]}})
        if dk["type"] in ref:
            m = copy.deepcopy(ref[dk["type"]])
            m["module_id"] = mid
            new_anchors.append(m)
            for an in m["anchors"]:
                if an["kind"] == "docking_port":
                    new_ports.append({"module_id": mid, "anchor_id": an["id"], "operational": "online",
                                      "occupancy": "free", "access": "allowed"})
    anchors["modules"][at_a:at_a] = new_anchors
    ports["ports"][at_p:at_p] = new_ports
    open(os.path.join(nav, "hub_semantic_anchors.json"), "w", encoding="utf-8", newline="\n").write(
        json.dumps(anchors, ensure_ascii=False, indent=2) + "\n")
    open(os.path.join(nav, "hub_docking_runtime_test.json"), "w", encoding="utf-8", newline="\n").write(
        json.dumps(ports, ensure_ascii=False, indent=2) + "\n")
    # the hub's traffic lanes (green, pre-written routes) and red zones, in the city frame (module <hub>.city):
    # src/assets/data/navigation/hub_lanes/<hub>.json, read by game::navigation::traffic::HubLaneNetwork
    lane_dir = os.path.join(nav, "hub_lanes")
    lane_path = os.path.join(lane_dir, f"{a.hub}.json")
    if L.get("lanes"):
        os.makedirs(lane_dir, exist_ok=True)
        open(lane_path, "w", encoding="utf-8", newline="\n").write(json.dumps({
            "schema": "elite.hub_lanes.v1", "hub_id": a.hub, "frame_module_id": f"{a.hub}.city",
            "description": "generated by tools/models/hub_belt_world.py from tools/models/units/hub_plane.py",
            "lanes": [{"id": ln["id"], "kind": ln.get("kind", "green"), "radius_m": ln["radius"], "max_speed_mps": ln["speed"], "max_ship_length_m": ln["max_ship_m"], "law": "assisted",
                       "stations_local_m": [list(q) for q in ln["stations"]]} for ln in L["lanes"]],
            "speed_limit_mps": 150.0,
            "speed_limit_zone_m": round(max(math.hypot(q[0], q[2]) for ln in L["lanes"] for q in ln["stations"]) + 2000.0),
            "connectors": [{"id": cn["id"], "from_lane": cn["from_lane"], "from_station": cn["from_station"],
                            "to_lane": cn["to_lane"], "to_station": cn["to_station"], "radius_m": cn["radius"],
                            "max_speed_mps": cn["speed"], "max_ship_length_m": cn["max_ship_m"],
                            "points_local_m": [list(q) for q in cn["points"]]} for cn in L.get("connectors", [])],
            "red_zones": [{"id": rz["id"], "center_local_m": list(rz["center"]), "half_extents_m": list(rz["half_extents"]),
                           "rotation_deg": list(rz["rotation_deg"])} for rz in L.get("red_zones", [])]},
            indent=1) + "\n")
    elif os.path.exists(lane_path):
        os.remove(lane_path)
    # the hub's PLAN for the game's Hub map (2D plan + 3D boxes): src/assets/data/navigation/hub_plans/<hub>.json
    plan_dir = os.path.join(nav, "hub_plans")
    plan_path = os.path.join(plan_dir, f"{a.hub}.json")
    if L.get("districts"):
        from hub_plan import air_fleet, plan_document, population_estimate
        plan = plan_document(a.hub, L)
        plan["population_estimate"] = population_estimate(plan)
        plan["air_fleet"] = air_fleet(a.hub, world)
        # the daily ship schedule (turnover -> visits -> docks): assets/data/navigation/hub_schedules/<hub>.json
        from hub_schedule import schedule_document
        sched = schedule_document(a.hub, L, plan)
        sched_dir = os.path.join(nav, "hub_schedules")
        os.makedirs(sched_dir, exist_ok=True)
        open(os.path.join(sched_dir, f"{a.hub}.json"), "w", encoding="utf-8", newline="\n").write(
            json.dumps(sched, ensure_ascii=False, indent=0) + "\n")
        print(f"{a.hub}: schedule {len(sched['visits'])} visits/day, docks {len(sched['docks'])}, demand {sched['demand']}")
        os.makedirs(plan_dir, exist_ok=True)
        open(plan_path, "w", encoding="utf-8", newline="\n").write(json.dumps(plan, ensure_ascii=False, indent=0) + "\n")
    elif os.path.exists(plan_path):
        os.remove(plan_path)
    at_h = next((k for k, h in enumerate(hubs) if h["id"] == a.hub), None)
    if at_h is None:
        world["orbital_hubs"] = hubs + [hub]
    else:
        world["orbital_hubs"] = hubs[:at_h] + [hub] + hubs[at_h + 1:]
    open(WORLD, "w", encoding="utf-8", newline="\n").write(json.dumps(world, ensure_ascii=False, indent=2) + "\n")
    open(os.path.join(ROOT, "src", "assets", "data", f"{a.hub}_haze.json"), "w", encoding="utf-8", newline="\n").write(
        json.dumps({"schema": "elite.hub_haze.v1", "hub": a.hub, "frame": "hub local metres (the dock modules' frame)",
                    "sources": L["haze"]}, indent=1) + "\n")
    # the legacy fallback proxies of the spinning modules (ObjectAssemblyRegistry): their coarse LOD as LOD0 OBJ
    for kid in ("hubb_ring_core", "hubb_hab_drum", "hubb_hotel_hex"):
        src = sorted(glob.glob(os.path.join(eqlib.SOURCE_MODELS, "hub", kid, "intact", "assembly", "LOD*", "*.obj")))[-1]
        dst = os.path.join(ROOT, "assets", "models", "hub", kid, "LOD0")
        os.makedirs(dst, exist_ok=True)
        shutil.copyfile(src, os.path.join(dst, kid + ".obj"))
    print(f"{a.hub}: city + {len(L['spinning'])} spinning bodies, {len(L['districts'])} districts, "
          f"{len(L['nodes'])} city nodes, {len(L['haze'])} haze sources -> {WORLD}")


if __name__ == "__main__":
    main()
