"""Stabilization stage 9: the inventory of the environment switches the game reads (getenv("ELITE_...")).

    python tools/dev_switch_inventory.py          -> docs/DEV_SWITCHES.md (regenerated; tracked)
    python tools/dev_switch_inventory.py check    -> exit 1 when a switch is new / gone against the tracked file

Classes:
  developer      ELITE_DEV_*: diagnostics, DEV scenarios, test scripts.
  configuration  everything else (server clock, economy state file, ship / route / dock tuning, map options, dumps,
                 cheats such as ELITE_FUEL_FREE): developer-build options.
  The preview package removes EVERY ELITE_* switch from its process at start (core::scrubDeveloperEnvironmentInPreview)
  except the preview-safe list PREVIEW_SAFE below.
"""
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "DEV_SWITCHES.md")
rx = re.compile(r'getenv\("(ELITE_[A-Z0-9_]+)"')
PREVIEW_SAFE = {"ELITE_SESSION_LOG", "ELITE_SERVER_OWN_CLOCK"}   # keep in step with BuildFlavor.cpp
uses = defaultdict(set)
for d, _, files in os.walk(os.path.join(ROOT, "src")):
    for f in files:
        if f.endswith((".cpp", ".h")):
            p = os.path.join(d, f)
            for m in rx.finditer(open(p, encoding="utf-8", errors="replace").read()):
                uses[m.group(1)].add(os.path.relpath(p, os.path.join(ROOT, "src")).replace("\\", "/"))
dev = sorted(k for k in uses if k.startswith("ELITE_DEV_"))
conf = sorted(k for k in uses if not k.startswith("ELITE_DEV_"))
lines = ["# Environment switches (generated by tools/dev_switch_inventory.py - do not edit by hand)", "",
         f"{len(uses)} switches: {len(dev)} developer (ELITE_DEV_*, removed in the preview package), "
         f"{len(conf)} configuration. The preview package removes all of them at start except "
         f"{', '.join(sorted(PREVIEW_SAFE))}.", "", "## Developer (ELITE_DEV_*)", "",
         "| switch | read in |", "|---|---|"]
lines += [f"| `{k}` | {', '.join(sorted(uses[k]))} |" for k in dev]
lines += ["", "## Configuration (developer build; preview-safe marked)", "", "| switch | preview | read in |", "|---|---|---|"]
lines += [f"| `{k}` | {'kept' if k in PREVIEW_SAFE else 'removed'} | {', '.join(sorted(uses[k]))} |" for k in conf]
text = "\n".join(lines) + "\n"
if len(sys.argv) > 1 and sys.argv[1] == "check":
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    known = set(re.findall(r"`(ELITE_[A-Z0-9_]+)`", old))
    added, gone = set(uses) - known, known - set(uses)
    if added or gone:
        print("[FAIL] the switch inventory changed - review and regenerate:", "new", sorted(added), "gone", sorted(gone))
        sys.exit(1)
    print(f"[PASS] switch inventory: {len(uses)} switches as recorded")
    sys.exit(0)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8", newline="\n").write(text)
print(f"{len(uses)} switches: {len(dev)} developer, {len(conf)} configuration -> {OUT}")
