#!/usr/bin/env python3
"""initial_world_state.json has ONE writer (tools/world_state_io.py) that merges the tools by world_state_owner
(architecture audit 2026-11-19: world_sites.py replaced every Sol hub, losing the hubs other tools had added)."""
from pathlib import Path
import json
import os
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import world_state_io as io  # noqa: E402

errors = []

# 1. the merge keeps every other writer's hubs
with tempfile.TemporaryDirectory() as d:
    path = os.path.join(d, "initial_world_state.json")
    doc = {"orbital_hubs": [
        {"id": "earth_orbital_hub", "system_id": 0},            # an old Sol hub (untagged, regenerated by sol_network)
        {"id": "belt_demo", "system_id": 0},                    # another tool's Sol hub (untagged)
        {"id": "site.005.colony.port01", "system_id": 5},       # a colony hub
    ]}
    io.save(doc, path)
    io.update(lambda x: io.replace_owned(x, "sol_network", [{"id": "earth_orbital_hub", "system_id": 0, "v": 2},
                                                           {"id": "luna_hub", "system_id": 0}]), path)
    io.update(lambda x: io.upsert_hub(x, {"id": "proto_district", "system_id": 0}, "hub_district_world"), path)
    io.update(lambda x: io.replace_owned(x, "sol_network", [{"id": "earth_orbital_hub", "system_id": 0, "v": 3}]), path)
    got = {h["id"]: h for h in io.load(path)["orbital_hubs"]}
    if set(got) != {"earth_orbital_hub", "belt_demo", "site.005.colony.port01", "proto_district"}:
        errors.append(f"merge lost / kept wrong hubs: {sorted(got)}")
    if got.get("earth_orbital_hub", {}).get("v") != 3 or got["earth_orbital_hub"].get(io.OWNER_KEY) != "sol_network":
        errors.append("the generator's own hub was not replaced")
    if "luna_hub" in got:
        errors.append("a hub the generator dropped from its set stayed (it owned it)")
    if got.get("proto_district", {}).get(io.OWNER_KEY) != "hub_district_world":
        errors.append("another tool's Sol hub lost its owner / was removed")
    if os.path.exists(path + ".lock") or os.path.exists(path + ".tmp"):
        errors.append("the lock or the temp file was left behind")

# 1b. a generator's hub keeps the modules another tool attached (the city of hub_belt_world.py --attach)
doc = {"orbital_hubs": [{"id": "earth_hub.tikhiy", "dock_modules": [
    {"id": "earth_hub.tikhiy.city", "type": "hub_belt_city", "generated": "hub_city"}]}]}
io.replace_owned(doc, "sol_network", [{"id": "earth_hub.tikhiy", "dock_modules": None}])
mods = doc["orbital_hubs"][0].get("dock_modules") or []
if [m["id"] for m in mods] != ["earth_hub.tikhiy.city"]:
    errors.append(f"the generator erased an attached city module: {mods}")

# 2. nobody else writes the file
for p in (ROOT / "tools").rglob("*.py"):
    if p.name == "world_state_io.py" or "__pycache__" in p.parts:
        continue
    text = p.read_text(encoding="utf-8", errors="replace")
    if "initial_world_state" not in text:
        continue
    for n, line in enumerate(text.splitlines(), 1):
        if re.search(r"open\((WORLD|RUNTIME_WORLD_STATE)\s*,\s*[\"']w", line):
            errors.append(f"{p.relative_to(ROOT)}:{n}: writes initial_world_state.json directly - use world_state_io")

if errors:
    for e in errors:
        print("FAIL", e)
    sys.exit(1)
print("World state writers check passed.")
