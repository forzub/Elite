#!/usr/bin/env python3
"""Ship model-asset SOURCE from the layout sketch (step 3, slices S1 + S2 data side; author 2026-11-09: "the hull in
compartments, interiors drawn only for a breached compartment").

Input: the hand-made layout sketch (tools/ships/layout_sketch.py: equipment installs, cover plates, hull outline) and
the equipment models (assets/models/equipment/<folder>/LOD1..3). Output: assets/models/ship_assets/<ship>/source/
  ship_asset.json  - the semantic assembly (nodes, states, compartments, openings, portals, collision, render LODs)
  geo/*.obj        - one merged mesh per equipment model and LOD (instanced by render nodes), hull / plates / pads
The C++ tool EliteShipAssetAssemble (tools/ship_asset_assemble) turns it into a compiled .elmodel through the
engine's own BUILD path.

Semantics:
  hull           - the exterior shell (sides, belly, top WITH cut-outs under the cover plates), hatches; always drawn;
  plate_<k>      - a radiator cover plate; state "breached" (torn off): the plate is not drawn, an Opening appears and
                   the exterior portal into compartment c_<k> opens;
  pad_<install>  - a reactor cooling pad (ER-5) on the back of its bay; "breached" opens the bay compartment;
  eq_<install>   - an equipment module (moduleId = the install). Inside a compartment footprint -> interior of that
                   compartment (drawn only behind an open, visible portal); hull-skin units (weapons, emitters, skids,
                   radar, dock, turret, the cockpit) are exterior;
  c20_<n>, shaft - containers and the inspection walkway: interior.
Collision: the ship hit volumes (plates: main volume while intact, seams always; equipment volumes; mount points).
usage: python tools/ships/ship_asset_source.py [cobrett-i]
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import layout_sketch as LS  # noqa: E402
from layout_sketch import Part, EQ, ROOT, MATERIALS, PADS  # noqa: E402

OUT = os.path.join(ROOT, "assets", "models", "ship_assets")
EXTERIOR_HINTS = ("laser", "missiles", "field_emitter", "skid", "radar", "dock", "pd1", "escape_cockpit")
# equipment LOD per asset render LOD: component LODs 0..2 use the units' LOD1 / LOD2 / LOD3, the shell LOD3 too
EQ_LOD = (1, 2, 3)


def merged_obj(folder, lod, only=None, skip=None):
    V, N, F = LS.load_obj(folder, lod, only=only, skip=skip)
    return V, N, F


def write_obj(path, V, N, F):
    out = ["# generated by tools/ships/ship_asset_source.py (do not edit)"]
    out += [f"v {x:.5f} {y:.5f} {z:.5f}" for x, y, z in V]
    NN = list(N) + [(0.0, 1.0, 0.0)] * max(0, len(V) - len(N))
    out += [f"vn {x:.4f} {y:.4f} {z:.4f}" for x, y, z in NN]
    for mat in sorted(F):
        out.append(f"usemtl {mat}")
        out += ["f " + " ".join(f"{i + 1}//{i + 1}" for i in f) for f in F[mat]]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


def part_mesh(part):
    return part.v, part.n, {m: [tuple(f) for f in fl] for m, fl in part.faces.items()}


def inside(poly, x, z):
    """point in polygon (x, z)"""
    c = False
    n = len(poly)
    for i in range(n):
        (x0, z0), (x1, z1) = poly[i], poly[(i + 1) % n]
        if (z0 > z) != (z1 > z) and x < (x1 - x0) * (z - z0) / (z1 - z0) + x0:
            c = not c
    return c


def hull_with_cutouts(outline, thick, holes, cell=0.25):
    """the hull shell: loft sides, belly fan, and the top surface rasterised in cells (run-length merged per row)
    with the cover-plate footprints left open"""
    h = Part("hull")
    n = len(outline)
    cx = sum(p[0] for p in outline) / n
    cz = sum(p[1] for p in outline) / n
    T = [(x, thick(x, z), z) for x, z in outline]
    B = [(x, -thick(x, z), z) for x, z in outline]
    for i in range(n):
        j = (i + 1) % n
        LS.quad(h, "sk_hull", [B[i], B[j], T[j], T[i]], LS.norm((outline[i][0] - cx, 0, outline[i][1] - cz)))
        h.face("sk_hull", [h.vert(B[i], (0, -1, 0)), h.vert(B[j], (0, -1, 0)), h.vert((cx, -thick(cx, cz), cz), (0, -1, 0))], (0, -1, 0))
    # the top: rows of trapezoids following the exact outline edges; the plate / bay holes are cut as straight
    # x-intervals (row edges snapped to the hole edges so no sliver remains)
    def span(zq):
        xs_ = []
        for i in range(n):
            (x0, z0), (x1, z1) = outline[i], outline[(i + 1) % n]
            if (z0 - zq) * (z1 - zq) <= 0 and z0 != z1:
                xs_.append(x0 + (x1 - x0) * (zq - z0) / (z1 - z0))
        return (min(xs_), max(xs_)) if len(xs_) >= 2 else None
    zs = sorted(set([p[1] for p in outline] + [h_[2] for h_ in holes] + [h_[3] for h_ in holes]))
    cuts = []
    for za, zb in zip(zs, zs[1:]):
        k = max(1, int(math.ceil((zb - za) / cell)))
        cuts += [za + (zb - za) * i / k for i in range(k)]
    cuts.append(zs[-1])
    for za, zb in zip(cuts, cuts[1:]):
        e = 1e-6
        sa, sb = span(za + e), span(zb - e)
        if not sa or not sb:
            continue
        zm = (za + zb) / 2
        hs = sorted((x0, x1) for x0, x1, z0, z1 in holes if z0 <= zm <= z1)
        pieces, left = [], ("edge", None)
        for x0, x1 in hs:
            pieces.append((left, ("x", x0)))
            left = ("x", x1)
        pieces.append((left, ("edge", None)))
        for (ka, va), (kb, vb) in pieces:
            xa0, xa1 = (sa[0], sb[0]) if ka == "edge" else (max(va, sa[0]), max(va, sb[0]))
            xb0, xb1 = (sa[1], sb[1]) if kb == "edge" else (min(vb, sa[1]), min(vb, sb[1]))
            if xb0 - xa0 < 1e-4 and xb1 - xa1 < 1e-4:
                continue
            q = [(xa0, thick(xa0, za), za), (xb0, thick(xb0, za), za), (xb1, thick(xb1, zb), zb), (xa1, thick(xa1, zb), zb)]
            LS.quad(h, "sk_hull", q, (0, 1, 0))
    return h


def euler(R):
    return LS._to_euler_xyz(R)


def build(name):
    P = LS.SHIPS[name]()
    installs = list(LS.INSTALLS)
    plates = list(LS.PLATES)
    H2 = LS.H2
    base = os.path.join(OUT, name, "source")
    geo = os.path.join(base, "geo")
    os.makedirs(geo, exist_ok=True)
    for f in os.listdir(geo):
        os.remove(os.path.join(geo, f))

    nodes, states, comps, openings, portals, collision = [], [], [], [], [], []
    lods = [{"level": k, "role": "component", "geometries": [], "nodes": []} for k in range(3)]
    lods.append({"level": 3, "role": "shell", "geometries": [], "nodes": []})
    geo_index = [dict() for _ in lods]

    def node(nid, module="", interior_of=None):
        nodes.append({"id": nid, "module": module})
        if interior_of is not None:
            comps[interior_of]["interior_nodes"].append(nid)
        return nid

    def geometry(lod_i, gid, V, N, F, two_sided=False):
        if gid in geo_index[lod_i]:
            return gid
        fn = f"{gid}.lod{lod_i}.obj"
        write_obj(os.path.join(geo, fn), V, N, F)
        lods[lod_i]["geometries"].append({"id": gid, "obj": "geo/" + fn, "two_sided": two_sided})
        geo_index[lod_i][gid] = True
        return gid

    def render(lod_i, rid, gid, nid, pos=(0, 0, 0), rot=(0, 0, 0), active=None):
        lods[lod_i]["nodes"].append({"id": rid, "geometry": gid, "node": nid, "position": [round(a, 5) for a in pos],
                                     "rotation_deg": list(rot), "active_states": active or []})

    # ---- compartments: one per cover plate (footprint x hull thickness) + one per propulsion bay
    for k, (pname, x0, x1, z0, z1, y) in enumerate(plates):
        comps.append({"id": f"c_{pname}", "role": "bay" if False else "compartment", "center": [(x0 + x1) / 2, 0.0, (z0 + z1) / 2],
                      "half_size": [(x1 - x0) / 2, H2, (z1 - z0) / 2], "interior_nodes": [], "plate": pname})
    bays = {}
    for nm, folder, R, pos in installs:
        if folder == "cobretty_er5_reactor":
            side = nm.split("_")[-1]
            bays[side] = len(comps)
            comps.append({"id": f"c_bay_{side}", "role": "propulsion_bay", "center": [pos[0], 0.0, pos[2]],
                          "half_size": [1.9, H2, 6.0], "interior_nodes": [], "plate": f"pad_eq_er5_{side}"})

    def compartment_of(x, y, z):
        for i, c in enumerate(comps):
            if all(abs(p - q) <= h + 1e-6 for p, q, h in zip((x, y, z), c["center"], c["half_size"])):
                return i
        return None

    # ---- hull shell with the plate cut-outs (+ hatches): exterior, every LOD
    outline = [(-2.6, -12.8), (2.6, -12.8), (5.4, -9.6), (10.2, -5.2), (12.6, 1.0), (12.6, 5.5), (10.2, 10.4),
               (-10.2, 10.4), (-12.6, 5.5), (-12.6, 1.0), (-10.2, -5.2), (-5.4, -9.6)]

    def thick(x, z):
        ax = abs(x)
        t = H2 if ax <= 10.2 else H2 - (ax - 10.2) * 0.42
        if z < -5.5:
            t = min(t, 1.45 + (z + 12.8) * 0.05)
        return t
    holes = [(x0, x1, z0, z1) for _, x0, x1, z0, z1, _ in plates]
    # the bays sit under their ER-5 pads: the top over each bay is open, the pad closes it
    for side, ci in bays.items():
        c = comps[ci]
        holes.append((c["center"][0] - 1.75, c["center"][0] + 1.75, c["center"][2] - 1.75, c["center"][2] + 1.75))
    hull = hull_with_cutouts(outline, thick, holes)
    for nm, part in P.items():
        if nm.startswith("hatch_"):
            for mat, fl in part.faces.items():
                for f in fl:
                    hull.face(mat, [hull.vert(part.v[i], part.n[i]) for i in f], part.n[f[0]])
    node("hull", "hull")
    for li in range(len(lods)):
        geometry(li, "hull", *part_mesh(hull))
        render(li, "hull", "hull", "hull")

    # ---- cover plates: breachable nodes
    for k, (pname, x0, x1, z0, z1, y) in enumerate(plates):
        nid = node(f"plate_{pname}", pname)
        states.append({"id": "breached", "display": "Torn off", "node": nid})
        cx, cz, w, l = (x0 + x1) / 2, (z0 + z1) / 2, x1 - x0, z1 - z0
        V, N, F = part_mesh(P[pname])
        for li in range(len(lods)):
            geometry(li, f"plate_{pname}", V, N, F, two_sided=True)
            render(li, f"plate_{pname}", f"plate_{pname}", nid, active=["intact"])
        openings.append({"id": f"open_{pname}", "node": nid, "position": [cx, y, cz], "rotation_deg": [-90, 0, 0],
                         "half_size": [w / 2, l / 2, 0.2], "active_states": ["breached"]})
        portals.append({"id": f"portal_{pname}", "a": f"c_{pname}", "b": None, "node": nid, "position": [cx, y, cz],
                        "rotation_deg": [-90, 0, 0], "half_size": [w / 2, l / 2, 0.1], "opening": f"open_{pname}"})

    # ---- equipment
    for nm, folder, R, pos in installs:
        # only the propulsion reactor's pad is hull skin (the back of its bay); service reactor pads stay inside
        has_pad = folder == "cobretty_er5_reactor" and os.path.exists(os.path.join(EQ, folder, "LOD1", PADS[0] + ".obj"))
        exterior = any(h in nm for h in EXTERIOR_HINTS)
        ci = None if exterior else compartment_of(*pos)
        if folder == "cobretty_er5_reactor":
            ci = bays[nm.split("_")[-1]]
        elif ci is None and not exterior:
            for side, bi in bays.items():                       # the CR-1 drives share the bay of their reactor
                if nm.endswith("_" + side) and abs(pos[0] - comps[bi]["center"][0]) < 0.5:
                    ci = bi
        nid = node(nm, nm, ci)
        rot = euler(R)
        for li, el in enumerate(EQ_LOD + (3,)):
            gid = f"{folder}" + ("_body" if has_pad else "")
            geometry(li, gid, *merged_obj(folder, el, skip=PADS if has_pad else None))
            render(li, nm, gid, nid, pos, rot)
        if has_pad:                                             # the pad: exterior, breachable (opens the bay)
            pid = node(f"pad_{nm}", nm)
            states.append({"id": "breached", "display": "Pad shot away", "node": pid})
            for li, el in enumerate(EQ_LOD + (3,)):
                geometry(li, f"{folder}_pad", *merged_obj(folder, el, only=PADS))
                render(li, f"pad_{nm}", f"{folder}_pad", pid, pos, rot, active=["intact"])
            if ci is not None:
                c = comps[ci]
                top = H2
                openings.append({"id": f"open_pad_{nm}", "node": pid, "position": [c["center"][0], top, c["center"][2]],
                                 "rotation_deg": [-90, 0, 0], "half_size": [1.75, 1.75, 0.2], "active_states": ["breached"]})
                portals.append({"id": f"portal_pad_{nm}", "a": c["id"], "b": None, "node": pid,
                                "position": [c["center"][0], top, c["center"][2]], "rotation_deg": [-90, 0, 0],
                                "half_size": [1.75, 1.75, 0.1], "opening": f"open_pad_{nm}"})

    # ---- containers and the walkway (interior)
    for nm, part in P.items():
        if not (nm.startswith("c20_") or nm.startswith("shaft_")):
            continue
        lo = [min(v[k] for v in part.v) for k in range(3)]
        hi = [max(v[k] for v in part.v) for k in range(3)]
        ci = compartment_of(*[(a + b) / 2 for a, b in zip(lo, hi)])
        nid = node(nm, nm, ci)
        for li in range(3):
            geometry(li, nm, *part_mesh(part))
            render(li, nm, nm, nid)

    # ---- collision from the ship hit volumes (plate main volume only while intact)
    vols, rules = LS.ship_hits()
    for v in vols:
        c = {"id": v["id"], "module": v["part"], "shape": v["shape"], "position": v["position"],
             "rotation_deg": v["rotation_deg"], "active_states": []}
        if v["shape"] == "box":
            c["half_size"] = v["half_size"]
        else:
            c["radius"], c["half_height"] = v["radius"], v["half_height"]
        if v.get("role") == "plate":
            c["node"] = f"plate_{v['part']}"
            c["active_states"] = ["intact"]
        collision.append(c)

    # ---- structural semantics: what is attached to what, and what breaks it (author 2026-11-10: "what is fixed
    #      through what, and where"). Plates: weld seams to the hull, broken by their 4 seam volumes; modules:
    #      equipment mounts to the hull, broken by their 4 mount points; a reactor pad: fixed to its reactor.
    byid = {v["id"]: v for v in vols}
    links, regions = [], []

    def proxy(vid):
        v = byid[vid]
        return {"id": vid, "position": v["position"], "rotation_deg": v["rotation_deg"], "half_size": v["half_size"]}
    node_ids = {n_["id"] for n_ in nodes}
    for r in rules["plates"]:
        pn = f"plate_{r['plate']}"
        links.append({"id": f"weld_{r['plate']}", "a": "hull", "b": pn, "kind": "weld_seam", "load_bearing": False,
                      "proxies": [proxy(x) for x in r["seams"]]})
        mv = byid[f"{r['plate']}.main"]
        regions.append({"id": f"hit_{r['plate']}", "node": pn, "position": mv["position"], "rotation_deg": mv["rotation_deg"],
                        "half_size": mv["half_size"], "active_states": ["intact"]})
    for r in rules["modules"]:
        if r["module"] not in node_ids:
            continue
        links.append({"id": f"mount_{r['module']}", "a": "hull", "b": r["module"], "kind": "equipment_mount", "load_bearing": True,
                      "proxies": [proxy(x) for x in r["mounts"]]})
    for n_ in nodes:
        if n_["id"].startswith("pad_") and n_["id"][4:] in node_ids:
            links.append({"id": f"fix_{n_['id']}", "a": n_["id"][4:], "b": n_["id"], "kind": "fixed_mount", "load_bearing": False,
                          "proxies": []})

    used = set()
    for lod in lods:
        for g in lod["geometries"]:
            for line in open(os.path.join(base, g["obj"]), encoding="utf-8"):
                if line.startswith("usemtl "):
                    used.add(line.split()[1])
    mats = {m: list(MATERIALS[m][0]) for m in sorted(used) if m in MATERIALS}
    doc = {"schema": "elite.ship_asset_source.v1", "asset_id": f"ship.{name}", "display_name": name,
           "generator": "tools/ships/ship_asset_source.py (do not edit)", "frame": "metres, +X right, +Y up, -Z forward",
           "materials": mats, "nodes": nodes, "states": states,
           "compartments": [{k: c[k] for k in ("id", "role", "center", "half_size", "interior_nodes")} for c in comps],
           "openings": openings, "portals": portals, "collision": collision, "render_lods": lods,
           "structural_links": links, "hit_regions": regions,
           # placement of THIS mesh in the object's logical frame (game basis, true metres -> identity, scale 1)
           "object_frame": {"position": [0.0, 0.0, 0.0], "rotation_deg": [0.0, 0.0, 0.0], "scale": 1.0},
           "catalog_id": "ship_" + name.replace("-", "_"),
           "release_rules": rules}
    open(os.path.join(base, "ship_asset.json"), "w", encoding="utf-8", newline="\n").write(json.dumps(doc, ensure_ascii=False, indent=1))
    LS.INSTALLS.clear()
    LS.PLATES.clear()
    inter = sum(len(c["interior_nodes"]) for c in comps)
    print(f"{name}: {len(nodes)} nodes ({inter} interior in {len(comps)} compartments), {len(states)} breachable, "
          f"{len(portals)} portals, {len(collision)} collision volumes, {len(links)} structural links, geometries per LOD "
          f"{[len(l['geometries']) for l in lods]} -> {base}")


if __name__ == "__main__":
    for n in (sys.argv[1:] or list(LS.SHIPS)):
        build(n)
