// EliteDamageCheck: the combat damage model on the production ShipCore (Cobra Mk I).
//   - the Cobra has runtime hit volumes from its mesh (panels, frame, equipment, seams);
//   - a laser beam heats the first panel on its line, burns through it in a time
//     set by power / armour / conduction, then reaches the frame behind it;
//   - a weak laser on thick armour never burns through (conduction wins);
//   - a shaped jet holes layers until its energy is spent; a slug stops stuck;
//   - destroying a part's links detaches it (structural runtime);
//   - a part impulse over the link tolerance breaks the links.
// usage: EliteDamageCheck [--dump]     (run from the build dir: assets/)
#include <cmath>
#include <cstdio>
#include <cstring>
#include <iostream>
#include <memory>
#include <string>

#include "src/game/combat/Penetration.h"
#include "src/game/combat/WeaponCatalog.h"
#include "src/game/geometry/ObjectAssemblyRegistry.h"
#include "src/game/ship/ShipInitData.h"
#include "src/game/ship/core/ShipCore.h"
#include "src/game/ship/descriptors/EliteCobraMk1.h"
#include "src/world/descriptors/ObjectDescriptorRegistry.h"

namespace
{
int failures = 0;

void check(bool ok, const std::string& what)
{
    std::cout << (ok ? "PASS " : "FAIL ") << what << "\n";
    if (!ok)
        ++failures;
}

std::unique_ptr<game::ship::core::ShipCore> spawnCobra()
{
    auto core = std::make_unique<game::ship::core::ShipCore>();
    core->init(ShipRole::NPC, EliteCobraMk1::EliteCobraMk1Descriptor(), glm::vec3(0.0f), ShipInitData {}, glm::mat4(1.0f));
    core->refreshRuntimeState();
    return core;
}

const game::damage::HitVolume* volume(const game::ship::core::ShipCore& core, const std::string& moduleId)
{
    for (const auto& v : core.hitComponent().volumes)
        if (!v.supportLinkVolume && v.moduleId == moduleId)
            return &v;
    return nullptr;
}

const world::modules::ObjectModuleState* module(const game::ship::core::ShipCore& core, const std::string& id)
{
    for (const auto& m : core.moduleRuntime().modules())
        if (m.moduleId == id)
            return &m;
    return nullptr;
}

void dump(const game::ship::core::ShipCore& core)
{
    const auto& vols = core.hitComponent().volumes;
    std::printf("hit volumes: %zu\n", vols.size());
    for (const auto& v : vols)
        std::printf("  %-34s %-28s L%d P%-3d c(%6.2f %6.2f %6.2f) h(%5.2f %5.2f %5.2f) hp %6.1f/%6.1f arm %5.1f pen %5.1f%s%s tol %.0f\n",
                    v.moduleId.c_str(), v.supportLinkVolume ? v.supportLinkId.substr(0, 28).c_str() : v.m_label.substr(0, 28).c_str(),
                    v.layerIndex, v.priority, v.center.x, v.center.y, v.center.z, v.halfSize.x, v.halfSize.y, v.halfSize.z,
                    v.health, v.maxHealth, v.armor, v.penetrationResistance, v.destructible ? " D" : "", v.supportLinkVolume ? " LINK" : "",
                    v.impulseTolerance);
    const auto& links = core.structuralLinkRuntime().links();
    std::printf("structural links: %zu\n", links.size());
    for (const auto& l : links)
        std::printf("  %-50s %-26s <- %-26s kind %d hp %.0f tol %.0f%s%s\n", l.id.substr(0, 50).c_str(), l.moduleAId.c_str(),
                    l.moduleBId.c_str(), static_cast<int>(l.kind), l.maxHealth, l.impulseTolerance, l.loadBearing ? " LB" : "",
                    l.autoGenerated ? " auto" : "");
    std::printf("modules: %zu, mass %.1f t\n", core.moduleRuntime().modules().size(), core.currentMassKg() / 1000.0);
}

// Fire a beam for up to `seconds` at 100 Hz; damage to the ShipCore every 0.2 s
// (the server's cadence). Returns the time of the first burn-through (-1 none).
double fireBeam(game::ship::core::ShipCore& core, game::combat::BurnState& burn, const glm::vec3& o, const glm::vec3& d,
                double powerMW, double seconds, std::string* firstKey = nullptr, std::string* secondKey = nullptr)
{
    const auto& mat = game::combat::weaponCatalog().materials;
    const double dt = 0.01;
    double firstBurn = -1.0, flush = 0.0;
    for (double t = 0.0; t < seconds; t += dt)
    {
        burn.cool(dt, mat);
        const auto hit = game::combat::stepBeam(core.hitComponent(), burn, o, d, 3000.0f, powerMW, dt, 0.1, mat);
        if (hit.hit && firstKey && firstKey->empty())
            *firstKey = hit.key;
        if (hit.hit && firstKey && secondKey && !firstKey->empty() && hit.key != *firstKey && secondKey->empty())
            *secondKey = hit.key;
        if (hit.burnedThrough > 0 && firstBurn < 0.0)
            firstBurn = t;
        flush += dt;
        if (flush >= 0.2 || hit.burnedThrough > 0)
        {
            flush = 0.0;
            for (const auto& [key, loss] : std::exchange(burn.pendingHealthLoss, {}))
                core.applyVolumeDamage(key, loss, game::damage::DamageType::Laser, world::coordinates::WorldPosition {});
        }
    }
    return firstBurn;
}
} // namespace

int main(int argc, char** argv)
{
    ObjectDescriptorRegistry::ensureInitialized();
    game::ship::geometry::ObjectAssemblyRegistry::ensureInitialized();
    auto cobra = spawnCobra();
    if (argc > 1 && std::strcmp(argv[1], "--dump") == 0)
    {
        dump(*cobra);
        return 0;
    }
    const auto& mat = game::combat::weaponCatalog().materials;
    check(game::combat::weaponCatalog().lasers.size() >= 3 && game::combat::weaponCatalog().missiles.size() >= 3,
          "weapons.json: 3 lasers, 3 missiles");
    check(cobra->hitComponent().volumes.size() > 50, "Cobra runtime hit volumes from its mesh: " +
                                                         std::to_string(cobra->hitComponent().volumes.size()));
    check(volume(*cobra, "ship_panel_side_LF") && volume(*cobra, "ship_frame_FL"), "side panel and frame volumes present");

    // ---- beam from the left at the left front side panel (it covers the left frame)
    const auto* panel = volume(*cobra, "ship_panel_side_LF");
    const glm::vec3 o(-60.0f, panel->center.y, panel->center.z);
    const glm::vec3 d(1.0f, 0.0f, 0.0f);
    {
        game::combat::BurnState burn;
        const auto hits = game::combat::castRay(cobra->hitComponent(), o, d, 200.0f);
        std::string first = hits.empty() ? "" : game::combat::volumeKey(cobra->hitComponent().volumes[hits.front().volume]);
        std::cout << "     ray from the left meets " << hits.size() << " volumes, first " << first << "\n";
        check(!hits.empty(), "a ray from the left meets the hull");
    }
    {
        auto ship = spawnCobra();
        game::combat::BurnState burn;
        std::string firstKey, secondKey;
        const double tPulse = fireBeam(*ship, burn, o, d, 0.75, 60.0, &firstKey, &secondKey);   // pulse 1.5 MW x duty 0.5
        const auto* p = volume(*ship, "ship_panel_side_LF");
        std::cout << "     pulse laser (0.75 MW mean): first " << firstKey << ", burn-through at " << tPulse << " s, then "
                  << secondKey << "; panel health " << (p ? p->health : -1.0f) << "\n";
        check(tPulse > 3.0 && tPulse < 40.0, "pulse laser burns through the side panel in 3..40 s (" + std::to_string(tPulse) + ")");
        check(!secondKey.empty() && secondKey != firstKey, "after the burn-through the beam reaches the next volume (" + secondKey + ")");
    }
    {
        auto ship = spawnCobra();
        game::combat::BurnState burn;
        std::string firstKey, secondKey;
        const double tMil = fireBeam(*ship, burn, o, d, 10.0, 10.0, &firstKey, &secondKey);
        std::cout << "     military laser 10 MW: burn-through at " << tMil << " s, then " << secondKey << "\n";
        check(tMil >= 0.0 && tMil < 2.0, "military laser burns through the panel in < 2 s (" + std::to_string(tMil) + ")");
    }
    {
        // conduction: a 0.15 MW-cooled spot under a 0.18 MW beam on armour 8 (absorbs 0.137 MW) never burns
        auto ship = spawnCobra();
        game::combat::BurnState burn;
        const double t = fireBeam(*ship, burn, o, d, 0.18, 60.0);
        check(t < 0.0, "a beam weaker than the spot's conduction never burns through (60 s)");
    }
    // ---- shaped jet straight in from the left: holes panel(s) and frame, spent inside
    {
        auto ship = spawnCobra();
        game::combat::BurnState burn;
        const auto res = game::combat::penetrate(ship->hitComponent(), burn, o, d, 200.0f, 30.0,
                                                 game::combat::WarheadKind::Shaped, 0.0, mat);
        std::cout << "     shaped jet 30 MJ:";
        for (const auto& l : res.layers)
            std::cout << " " << l.key << (l.holed ? "(through " : "(spent ") << l.spentMJ << ")";
        std::cout << (res.exited ? " exited" : " spent") << "\n";
        check(res.layers.size() >= 2 && res.layers.front().holed, "shaped jet holes the outer layer and goes deeper");
        check(!res.exited, "a 30 MJ jet is spent inside the Cobra");
        for (const auto& [key, loss] : std::exchange(burn.pendingHealthLoss, {}))
            ship->applyVolumeDamage(key, loss, game::damage::DamageType::Explosion, world::coordinates::WorldPosition {});
        const auto* p = volume(*ship, "ship_panel_side_LF");
        check(!p || p->health < p->maxHealth, "the jet's damage reached the ShipCore (panel health down)");
    }
    {
        auto ship = spawnCobra();
        game::combat::BurnState burn;
        const double ke = 0.5 * 40.0 * 1200.0 * 1200.0 / 1.0e6;   // 40 kg at 1.2 km/s = 28.8 MJ
        const auto res = game::combat::penetrate(ship->hitComponent(), burn, o, d, 200.0f, ke, game::combat::WarheadKind::Slug,
                                                 40.0, mat);
        std::cout << "     slug " << ke << " MJ:";
        for (const auto& l : res.layers)
            std::cout << " " << l.key << (l.holed ? "(through " : "(spent ") << l.spentMJ << ")";
        std::cout << (res.stuck ? " STUCK" : res.exited ? " exited" : "") << "\n";
        check(res.stuck && burn.stuck.size() == 1, "a 40 kg slug at 1.2 km/s stops stuck inside the hull");
        const double ke2 = 0.5 * 40.0 * 6000.0 * 6000.0 / 1.0e6;
        game::combat::BurnState burn2;
        const auto res2 = game::combat::penetrate(ship->hitComponent(), burn2, o, d, 200.0f, ke2, game::combat::WarheadKind::Slug,
                                                  40.0, mat);
        check(res2.exited && !res2.stuck, "the same slug at 6 km/s goes through the hull and out");
    }
    // ---- structure: the left laser hangs on the left front frame
    {
        auto ship = spawnCobra();
        const auto* laser = module(*ship, "ship_laser_L");
        check(laser && laser->isAttachedLike(), "laser L attached at start");
        const int broken = ship->applyPartImpulse("ship_laser_L", 2000.0);
        const auto* after = module(*ship, "ship_laser_L");
        std::cout << "     2000 kN s on laser L: " << broken << " links broken, state " << (after ? int(after->state) : -1) << "\n";
        check(broken >= 1, "an impulse over the tolerance breaks the laser's mount");
        check(after && !after->isAttachedLike(), "laser L no longer attached after its mount broke");
        auto ship2 = spawnCobra();
        const int broken2 = ship2->applyPartImpulse("ship_laser_L", 100.0);
        const auto* l2 = module(*ship2, "ship_laser_L");
        check(broken2 == 0 && l2 && l2->isAttachedLike(), "a small impulse only fatigues the mount");
    }
    {
        // the frame the laser hangs on destroyed by fire -> the laser goes with it
        auto ship = spawnCobra();
        ship->applyVolumeDamage("module::ship_frame_FL", 1.0e6, game::damage::DamageType::Laser, world::coordinates::WorldPosition {});
        const auto* frame = module(*ship, "ship_frame_FL");
        const auto* laser = module(*ship, "ship_laser_L");
        std::cout << "     frame FL destroyed: frame state " << (frame ? int(frame->state) : -1) << ", laser L state "
                  << (laser ? int(laser->state) : -1) << "\n";
        // The frame's policy is DisableOnly: it stays as a dead wreck (health 0).
        check(frame && (frame->isDestroyedLike() || frame->health <= 0.0f), "frame FL destroyed by damage");
        check(laser && !laser->isAttachedLike(), "laser L loses its support with the frame (dependency tree)");
    }
    std::cout << (failures ? "DAMAGE CHECK FAILED" : "DAMAGE CHECK PASSED") << " (" << failures << " failures)\n";
    return failures ? 1 : 0;
}
