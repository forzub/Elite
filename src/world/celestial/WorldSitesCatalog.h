#pragma once

#include <fstream>
#include <map>
#include <string>
#include <vector>

#include <nlohmann/json.hpp>

namespace world::celestial
{
/*
    World sites of 3126: hubs, settlements, ports, mining / industrial /
    military / science hubs, free ports (the spatial civilisation layer).

    The file galaxy_details/world_sites/sites_3126.json is GENERATED by
    tools/colonization_lab/world_sites.py from the world model; it is a
    read-only copy, never a second source of truth. One site id = one world
    object; a map marker is only its presentation. A site with a
    runtimeBinding (e.g. earth_orbital_hub, initial_world_state.orbital_hubs)
    is already a replicated runtime hub, so maps must not draw it twice.
*/
enum class WorldSitePlacementKind
{
    None = 0,
    Orbit,
    Surface,
    Belt,
    Lagrange
};

struct WorldSite
{
    std::string id;
    std::string name;
    std::string type;          // site_types key of canon/world_sites.json
    std::string mapLevel;      // "system" | "detail" | "galaxy" | "none"
    std::string polity;
    std::string parentBodyId;  // runtime body / reservoir id
    std::string runtimeBinding;
    int systemId = -1;
    long long population = 0;

    WorldSitePlacementKind placement = WorldSitePlacementKind::None;
    double altitudeKm = 0.0;
    double inclinationDeg = 0.0;
    double latitudeDeg = 0.0;
    double longitudeDeg = 0.0;
    double beltRadiusAu = 0.0;
    double beltLongitudeDeg = 0.0;
    std::string lagrangePoint; // "L4" / "L5"
};

class WorldSitesCatalog
{
public:
    bool loadFromRuntimeOrSource()
    {
        for (const char* root : {
                "assets/data/galaxy_details",
                "../assets/data/galaxy_details",
                "../src/assets/data/galaxy_details"})
        {
            if (load(std::string(root) + "/world_sites/sites_3126.json"))
                return true;
        }
        return false;
    }

    bool load(const std::string& path)
    {
        std::ifstream in(path);
        if (!in)
            return false;
        nlohmann::json root;
        try
        {
            in >> root;
        }
        catch (const std::exception&)
        {
            return false;
        }
        if (!root.is_object() || root.value("schema", std::string()) != "elite.world_sites_runtime.v1" ||
            !root.contains("sites") || !root["sites"].is_array())
        {
            return false;
        }
        m_bySystem.clear();
        for (const auto& j : root["sites"])
        {
            WorldSite s;
            s.id = j.value("id", std::string());
            s.name = j.value("name", std::string());
            s.type = j.value("type", std::string());
            s.mapLevel = j.value("map_level", std::string());
            s.polity = j["polity"].is_string() ? j["polity"].get<std::string>() : std::string();
            s.parentBodyId = j["parent_body_id"].is_string() ? j["parent_body_id"].get<std::string>() : std::string();
            s.runtimeBinding = j["runtime_binding"].is_string() ? j["runtime_binding"].get<std::string>() : std::string();
            s.systemId = j.value("system_id", -1);
            s.population = j.value("population", 0LL);
            const auto& p = j.contains("placement") ? j["placement"] : nlohmann::json::object();
            if (p.contains("orbit"))
            {
                const auto& o = p["orbit"];
                if (o.contains("lagrange"))
                {
                    s.placement = WorldSitePlacementKind::Lagrange;
                    s.lagrangePoint = o.value("lagrange", std::string("L4"));
                }
                else
                {
                    s.placement = WorldSitePlacementKind::Orbit;
                    s.altitudeKm = o.value("altitude_km", 0.0);
                    s.inclinationDeg = o.value("inclination_deg", 0.0);
                }
            }
            else if (p.contains("surface"))
            {
                s.placement = WorldSitePlacementKind::Surface;
                s.latitudeDeg = p["surface"].value("lat_deg", 0.0);
                s.longitudeDeg = p["surface"].value("lon_deg", 0.0);
            }
            else if (p.contains("belt"))
            {
                s.placement = WorldSitePlacementKind::Belt;
                s.beltRadiusAu = p["belt"].value("radius_au", 0.0);
                s.beltLongitudeDeg = p["belt"].value("longitude_deg", 0.0);
            }
            if (s.id.empty() || s.systemId < 0 || s.placement == WorldSitePlacementKind::None)
                continue;
            m_bySystem[s.systemId].push_back(std::move(s));
        }
        m_loaded = true;
        return true;
    }

    bool loaded() const { return m_loaded; }

    const std::vector<WorldSite>& sitesInSystem(int systemId) const
    {
        static const std::vector<WorldSite> none;
        const auto it = m_bySystem.find(systemId);
        return it == m_bySystem.end() ? none : it->second;
    }

private:
    bool m_loaded = false;
    std::map<int, std::vector<WorldSite>> m_bySystem;
};
}
