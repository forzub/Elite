"""National banks 3126: one central bank + currency per polity (offline, deterministic, stdlib only).

Inputs: canon/national_banks.json (names, currency unit scales, regime -> institutional quality, shared rules,
price-step constants - PROPOSAL), out/world_3126/economy_3126.json (GENERATED by world_economy.py: growth, GDP per
head, population, regime, home system of every polity), src/assets/data/economy/economy_rules.json (GENERATED by
economy_live.py: blocs and the bloc channel matrix).

Output (GENERATED, never edited by hand): src/assets/data/economy/national_banks.json - read by the server economy
(src/game/economy/EconomyServer.cpp). Model and formulas: docs/ECONOMY_BANKING.md.

    python national_banks.py           # derive and write the runtime file
    python national_banks.py --check   # recompute, compare with the file, run the plausibility checks
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
CANON = os.path.join(HERE, "canon", "national_banks.json")
ECONOMY = os.path.join(HERE, "out", "world_3126", "economy_3126.json")
RULES = os.path.join(ROOT, "src", "assets", "data", "economy", "economy_rules.json")
OUT = os.path.join(ROOT, "src", "assets", "data", "economy", "national_banks.json")


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def r5(x):
    return round(x, 5)


def build():
    canon = load(CANON)
    economy = load(ECONOMY)
    rules = load(RULES)
    a = canon["anchors"]
    polities = economy["polities"]
    sol_gpc = polities["sol_authority"]["gdp_per_capita_cr"]
    bloc_of = {}
    for bloc, members in rules["blocs_members"].items():
        for m in members:
            bloc_of[m] = bloc

    banks = []
    for pid in sorted(canon["banks"]):
        names = canon["banks"][pid]
        p = polities[pid]
        q = canon["regime_quality"][p["regime"]]
        small = p["population"] < a["small_economy_population"]
        growth = max(0.0, p.get("growth_per_year", 0.01))
        inflation = a["inflation_target_stable"] + a["inflation_extra_weak"] * (1.0 - q)
        risk = a["country_risk_weak"] * (1.0 - q) + (a["small_economy_premium"] if small else 0.0)
        policy = a["neutral_real_rate"] + growth + inflation + risk
        reserve = names.get("peg") == "reserve"
        if reserve:
            fx, sigma, band = 1.0, 0.0, 0.0
        else:
            level = (sol_gpc / max(1.0, p["gdp_per_capita_cr"])) ** a["balassa_samuelson_exponent"]
            fx = names["unit_scale"] * level
            sigma = a["fx_sigma_stable_per_day"] + a["fx_sigma_weak_extra_per_day"] * (1.0 - q) + \
                (a["fx_sigma_small_extra_per_day"] if small else 0.0)
            band = a["fx_band_stable"] + a["fx_band_weak_extra"] * (1.0 - q)
        banks.append({
            "id": pid,
            "polity_name": p["name"],
            "bank": names["bank"],
            "currency": names["currency"],
            "code": names["code"],
            "bloc": bloc_of.get(pid, "nonaligned:" + pid),
            "system_id": p["system"],
            "regime": p["regime"],
            "quality": q,
            "population": p["population"],
            "inflation": r5(inflation),
            "policy_rate": r5(policy),
            "deposit_rate": r5(max(0.0, policy + a["deposit_spread"])),
            "loan_rate": r5(policy + a["secured_loan_spread"]),
            "overdraft_rate": r5(policy + a["overdraft_spread"]),
            "lifeline_rate": r5(policy + canon["rules"]["lifeline_spread"]),
            "reserve": reserve,
            "fx_anchor_per_cr": r5(fx),
            "fx_sigma_day": r5(sigma),
            "fx_half_life_days": a["fx_half_life_days"],
            "fx_band": r5(band),
            "status": "PROPOSAL",
        })

    return {
        "schema": "national_banks/1",
        "status": "PROPOSAL",
        "generated_by": "tools/colonization_lab/national_banks.py (canon/national_banks.json + out/world_3126/economy_3126.json + economy_rules.json blocs)",
        "do_not_edit": True,
        "note": "One national bank and currency per polity; Cr = the Sol Authority credit (reserve / settlement unit, all goods prices in Cr). Rates are annual, fx = local units per 1 Cr. See docs/ECONOMY_BANKING.md.",
        "banks": banks,
        "no_bank": {k: {"note": v, "lifeline_bank": "gj832_tianhe"} for k, v in canon["no_bank"].items()},
        "bloc_matrix": rules["blocs"]["matrix"],
        "rules": canon["rules"],
        "prices": canon["prices"],
    }


def checks(doc):
    problems = []
    for b in doc["banks"]:
        if not (0.0 <= b["deposit_rate"] < b["policy_rate"] < b["loan_rate"] < b["overdraft_rate"]):
            problems.append(f"{b['id']}: rate ladder broken")
        if not (0.02 <= b["policy_rate"] <= 0.15):
            problems.append(f"{b['id']}: policy rate {b['policy_rate']} outside 2-15 %")
        if b["fx_anchor_per_cr"] <= 0.0:
            problems.append(f"{b['id']}: fx <= 0")
        if b["fx_sigma_day"] > 0.02:
            problems.append(f"{b['id']}: fx sigma {b['fx_sigma_day']} > 2 % a day")
    reserve = [b for b in doc["banks"] if b["reserve"]]
    if len(reserve) != 1 or reserve[0]["code"] != "CR":
        problems.append("exactly one reserve bank (CR) expected")
    codes = [b["code"] for b in doc["banks"]]
    if len(set(codes)) != len(codes):
        problems.append("duplicate currency codes")
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    doc = build()
    text = json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
    problems = checks(doc)
    if args.check:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("national_banks: file " + ("up to date" if same else "DIFFERS"))
        for p in problems:
            print("FAIL " + p)
        print(f"national_banks: {len(doc['banks'])} banks, checks " + ("OK" if not problems else f"{len(problems)} FAIL"))
        return 0 if same and not problems else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    for b in doc["banks"]:
        print(f"{b['id']:22s} {b['code']} policy {b['policy_rate']*100:5.2f} %  deposit {b['deposit_rate']*100:5.2f} %  "
              f"overdraft {b['overdraft_rate']*100:5.2f} %  fx {b['fx_anchor_per_cr']:9.3f}/Cr  sigma {b['fx_sigma_day']*100:.2f} %/d  [{b['bloc']}]")
    for p in problems:
        print("FAIL " + p)
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
